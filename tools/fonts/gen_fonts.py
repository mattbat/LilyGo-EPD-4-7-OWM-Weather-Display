#!/usr/bin/env python3
"""Generate the portable bitmap fonts in src/fonts/ from Atkinson Hyperlegible.

Runs LilyGo's scripts/fontconvert.py (uncompressed, 4-bit glyph bitmaps) once per
font/size with a custom code point list, then renames its types (GFXglyph, GFXfont,
UnicodeInterval) to our portable EGlyph/EFont/EInterval so nothing clashes with
epd_driver.h, and writes one header per font.

Usage:  python tools/fonts/gen_fonts.py [path/to/fontconvert.py]
Needs:  pip install freetype-py
fontconvert.py is found in .pio/libdeps/*/LilyGo-EPD47/scripts/ after a t5-47 build
(it is GPL, so it is not vendored here).

U+2191/U+2193 arrows are missing from Atkinson Hyperlegible, so Noto Sans Symbols
(OFL) is the fallback face for them.
"""
import glob, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "fonts")

REGULAR = os.path.join(HERE, "AtkinsonHyperlegible-Regular.ttf")
BOLD = os.path.join(HERE, "AtkinsonHyperlegible-Bold.ttf")
SYMBOLS = os.path.join(HERE, "NotoSansSymbols.ttf")

# (name prefix, ttf, sizes, code point intervals); sizes are em height in pixels
FULL = [(0x20, 0x7E), (0xB0, 0xB0), (0xB7, 0xB7), (0x2013, 0x2014),
        (0x2191, 0x2191), (0x2193, 0x2193), (0x2212, 0x2212)]
# space . - digits / and the degree sign, U+2212 minus
DIGITS = [(0x20, 0x20), (0x2D, 0x2F), (0x30, 0x39), (0xB0, 0xB0), (0x2212, 0x2212)]

JOBS = [
    ("AtkR", REGULAR, [20, 22, 24, 28, 44], FULL),
    ("AtkB", BOLD, [20, 22, 24, 28, 34, 46, 50, 56, 76], FULL),
    ("AtkB", BOLD, [136, 170], DIGITS),
]


def find_fontconvert():
    if len(sys.argv) > 1:
        return sys.argv[1]
    hits = glob.glob(os.path.join(HERE, "..", "..", ".pio", "libdeps", "*", "LilyGo-EPD47", "scripts", "fontconvert.py"))
    if not hits:
        sys.exit("fontconvert.py not found; run `pio run -e t5-47` first or pass its path")
    return hits[0]


def patched_script(src_path, intervals):
    src = open(src_path, encoding="utf-8").read()
    block = "intervals = [\n" + "".join(f"    ({a}, {b}),\n" for a, b in intervals) + "]\n"
    new, n = re.subn(r"intervals = \[.*?\n\]\n", lambda m: block, src, count=1, flags=re.S)
    if n != 1:
        sys.exit("could not patch intervals in fontconvert.py")
    # fontconvert assumes 150 dpi (size = points). We want size = pixels (the plan's sizes are
    # CSS px from the mockups), which is 72 dpi.
    if "150, 150" not in new:
        sys.exit("could not patch dpi in fontconvert.py")
    new = new.replace("150, 150", "72, 72")
    return new


def convert(script, name, ttf, size, intervals):
    with tempfile.TemporaryDirectory() as td:
        p = os.path.join(td, "fc.py")
        open(p, "w", encoding="utf-8").write(patched_script(script, intervals))
        r = subprocess.run([sys.executable, p, name, str(size), ttf, SYMBOLS],
                           capture_output=True, text=True, encoding="utf-8",
                           env=dict(os.environ, PYTHONIOENCODING="utf-8"))
    if r.returncode != 0:
        sys.exit(f"fontconvert failed for {name}: {r.stderr}")
    text = r.stdout.replace("\r\n", "\n")
    text = text.replace('#include "epd_driver.h"', '#include "efont.h"')
    text = text.replace("GFXglyph", "EGlyph").replace("UnicodeInterval", "EInterval").replace("GFXfont", "EFont")
    text = text.replace(f"const EFont {name} =", f"extern const EFont {name} =")
    # keep the helper arrays private to the one translation unit that includes us
    text = re.sub(r"^const (uint8_t|EGlyph|EInterval) ", r"static const \1 ", text, flags=re.M)
    text = "".join(c if ord(c) < 128 else f"U+{ord(c):04X}" for c in text)
    return ("// GENERATED by tools/fonts/gen_fonts.py - do not edit.\n" + text)


def main():
    script = find_fontconvert()
    os.makedirs(OUT, exist_ok=True)
    names = []
    for prefix, ttf, sizes, intervals in JOBS:
        for s in sizes:
            name = f"{prefix}{s}"
            names.append((name, s))
            with open(os.path.join(OUT, f"{name.lower()}.h"), "w", newline="\n") as f:
                f.write(convert(script, name, ttf, s, intervals))
            print("generated", name)
    names.sort(key=lambda t: (t[0][:4], t[1]))
    with open(os.path.join(OUT, "fonts_all.h"), "w", newline="\n") as f:
        f.write("// GENERATED by tools/fonts/gen_fonts.py - do not edit.\n#pragma once\n")
        for n, _ in names:
            f.write(f'#include "{n.lower()}.h"\n')
    with open(os.path.join(OUT, "fonts.h"), "w", newline="\n") as f:
        f.write("// GENERATED by tools/fonts/gen_fonts.py - do not edit.\n#pragma once\n#include \"efont.h\"\n\n")
        f.write("// AtkR<size> = Atkinson Hyperlegible Regular, AtkB<size> = Bold (size = em height in pixels).\n")
        f.write("// AtkB136 and AtkB170 contain only space . - / digits and the degree sign.\n")
        for n, _ in names:
            f.write(f"extern const EFont {n};\n")


if __name__ == "__main__":
    main()
